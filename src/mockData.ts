function buildClaim(s: Seed): Claim {
  return {
    id: s.claimNumber.toLowerCase().replace('-', ''),
    claimNumber: s.claimNumber,
    policyholder: s.policyholder,
    type: s.type,
    stage: s.stage,
    amount: s.amount,
    priority: s.priority,
    filedDate: daysAgo(s.filedDaysAgo),
    closedDate: s.closedDaysAgo != null ? daysAgo(s.closedDaysAgo) : null,
    description: s.description,
    adjuster: s.adjuster,
    documents: s.docs.map(([name, type, pages], i) => ({
      id: `${s.claimNumber.toLowerCase().replace('-', '')}-doc-${i + 1}`,
      name,
      type,
      size: `${(0.3 + ((i * 37 + s.amount) % 40) / 10).toFixed(1)} MB`,
      pages,
      uploadedAt: daysAgo(Math.max(0, s.filedDaysAgo - i)),
    })),
    aiSummary: s.aiSummary,
  };
}

export const claims: Claim[] = seeds.map(buildClaim);
